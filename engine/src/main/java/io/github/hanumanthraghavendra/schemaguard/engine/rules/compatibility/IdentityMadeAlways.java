package io.github.hanumanthraghavendra.schemaguard.engine.rules.compatibility;

import io.github.hanumanthraghavendra.schemaguard.engine.diff.Change;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Identity;
import io.github.hanumanthraghavendra.schemaguard.engine.rules.Category;
import io.github.hanumanthraghavendra.schemaguard.engine.rules.ChangeRule;
import io.github.hanumanthraghavendra.schemaguard.engine.rules.Finding;
import io.github.hanumanthraghavendra.schemaguard.engine.rules.Operation;
import io.github.hanumanthraghavendra.schemaguard.engine.rules.RiskLevel;
import io.github.hanumanthraghavendra.schemaguard.engine.rules.RuleContext;
import io.github.hanumanthraghavendra.schemaguard.engine.rules.RuleInfo;
import java.util.Optional;

/**
 * An identity column that changes from BY DEFAULT to ALWAYS.
 */
public final class IdentityMadeAlways extends ChangeRule<Change.ColumnIdentityChanged> {

    public IdentityMadeAlways() {
        super(
                Change.ColumnIdentityChanged.class,
                new RuleInfo(
                        "SG-R507",
                        "identity-made-always",
                        Category.COMPATIBILITY,
                        RiskLevel.LOW,
                        "Identity changes to GENERATED ALWAYS",
                        "With GENERATED BY DEFAULT an INSERT may supply its own value for the column. With "
                                + "GENERATED ALWAYS that INSERT is rejected. Data imports, copies between environments "
                                + "and tests that set ids often do exactly that.",
                        "Check that nothing sets the column itself. The places that must do so can add "
                                + "OVERRIDING SYSTEM VALUE to their INSERT."));
    }

    @Override
    protected Optional<Finding> evaluate(Change.ColumnIdentityChanged change, RuleContext context) {
        if (change.before() != Identity.BY_DEFAULT || change.after() != Identity.ALWAYS || !context.kept(change.table())) {
            return Optional.empty();
        }
        String message =
                change.table() + "." + change.column() + " changes to GENERATED ALWAYS. An INSERT that supplies its own value"
                        + " for the column is rejected from now on.";
        return found(change, message, Operation.SET_IDENTITY);
    }
}
