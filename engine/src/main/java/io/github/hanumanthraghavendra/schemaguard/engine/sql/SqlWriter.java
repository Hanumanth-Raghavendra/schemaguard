package io.github.hanumanthraghavendra.schemaguard.engine.sql;

import io.github.hanumanthraghavendra.schemaguard.engine.model.Catalog;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Check;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Column;
import io.github.hanumanthraghavendra.schemaguard.engine.model.ColumnRef;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Constraint;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Deferrability;
import io.github.hanumanthraghavendra.schemaguard.engine.model.EnumType;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Expression;
import io.github.hanumanthraghavendra.schemaguard.engine.model.ForeignKey;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Identifiers;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Index;
import io.github.hanumanthraghavendra.schemaguard.engine.model.IndexColumn;
import io.github.hanumanthraghavendra.schemaguard.engine.model.MatchType;
import io.github.hanumanthraghavendra.schemaguard.engine.model.NullsOrder;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Persistence;
import io.github.hanumanthraghavendra.schemaguard.engine.model.PrimaryKey;
import io.github.hanumanthraghavendra.schemaguard.engine.model.ReferentialAction;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Sequence;
import io.github.hanumanthraghavendra.schemaguard.engine.model.SortOrder;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Table;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Unique;
import io.github.hanumanthraghavendra.schemaguard.engine.parser.Expressions;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Collectors;

/**
 * Writes model objects back as PostgreSQL DDL.
 *
 * <p>Every fragment is valid SQL that the {@link io.github.hanumanthraghavendra.schemaguard.engine.parser.Parser} reads back into an equal
 * object; {@link #script(Catalog)} writes a whole catalog the way {@code pg_dump} would order
 * it. Both properties are tested, and the scripts are checked against a real PostgreSQL.
 */
public final class SqlWriter {

    private SqlWriter() {}

    // ---------------------------------------------------------------- names and literals

    public static String name(String identifier) {
        return Identifiers.quoteIfNeeded(identifier);
    }

    public static String names(List<String> identifiers) {
        return identifiers.stream().map(SqlWriter::name).collect(Collectors.joining(", "));
    }

    public static String literal(String value) {
        return "'" + value.replace("'", "''") + "'";
    }

    // ---------------------------------------------------------------- columns

    /** A column definition as it appears inside CREATE TABLE, starting with the column name. */
    public static String column(Column column) {
        return name(column.name()) + " " + columnAttributes(column);
    }

    /** A column definition without its name: the type and every clause that follows it. */
    public static String columnAttributes(Column column) {
        StringBuilder sql = new StringBuilder(column.type().toSql());
        column.collation().ifPresent(collation -> sql.append(" COLLATE ").append(collation));
        column.defaultValue().ifPresent(value -> sql.append(" DEFAULT ").append(defaultExpression(value)));
        column.generated()
                .ifPresent(
                        generated ->
                                sql.append(" GENERATED ALWAYS AS (")
                                        .append(generated.expression().sql())
                                        .append(generated.stored() ? ") STORED" : ") VIRTUAL"));
        switch (column.identity()) {
            case ALWAYS -> sql.append(" GENERATED ALWAYS AS IDENTITY");
            case BY_DEFAULT -> sql.append(" GENERATED BY DEFAULT AS IDENTITY");
            case NONE -> {
                // Not an identity column.
            }
        }
        if (column.notNull()) {
            sql.append(" NOT NULL");
        }
        return sql.toString();
    }

    /** A default value, in parentheses only where the grammar of DEFAULT requires them. */
    public static String defaultExpression(Expression value) {
        return Expressions.needsParenthesesAsDefault(value) ? "(" + value.sql() + ")" : value.sql();
    }

    // ---------------------------------------------------------------- constraints

    /** A constraint as it appears in CREATE TABLE or ALTER TABLE ... ADD, with its name if it has one. */
    public static String constraint(Constraint constraint) {
        String prefix = constraint.name().map(n -> "CONSTRAINT " + name(n) + " ").orElse("");
        return prefix + constraintBody(constraint);
    }

    /** A constraint definition without its name, for example {@code UNIQUE (email)}. */
    public static String constraintBody(Constraint constraint) {
        return switch (constraint) {
            case PrimaryKey pk ->
                    "PRIMARY KEY (" + names(pk.columns()) + ")" + include(pk.include()) + deferrability(pk.deferrability());
            case Unique unique ->
                    "UNIQUE"
                            + (unique.nullsNotDistinct() ? " NULLS NOT DISTINCT" : "")
                            + " ("
                            + names(unique.columns())
                            + ")"
                            + include(unique.include())
                            + deferrability(unique.deferrability());
            case ForeignKey fk -> foreignKey(fk);
            case Check check ->
                    "CHECK ("
                            + check.expression().sql()
                            + ")"
                            + (check.noInherit() ? " NO INHERIT" : "")
                            + (check.notValid() ? " NOT VALID" : "");
        };
    }

    private static String foreignKey(ForeignKey fk) {
        StringBuilder sql =
                new StringBuilder("FOREIGN KEY (")
                        .append(names(fk.columns()))
                        .append(") REFERENCES ")
                        .append(fk.referencedTable().toSql());
        if (!fk.referencedColumns().isEmpty()) {
            sql.append(" (").append(names(fk.referencedColumns())).append(')');
        }
        if (fk.match() != MatchType.SIMPLE) {
            sql.append(" MATCH ").append(fk.match().name());
        }
        if (fk.onDelete() != ReferentialAction.NO_ACTION) {
            sql.append(" ON DELETE ").append(action(fk.onDelete()));
            if (!fk.onDeleteColumns().isEmpty()) {
                sql.append(" (").append(names(fk.onDeleteColumns())).append(')');
            }
        }
        if (fk.onUpdate() != ReferentialAction.NO_ACTION) {
            sql.append(" ON UPDATE ").append(action(fk.onUpdate()));
        }
        sql.append(deferrability(fk.deferrability()));
        if (fk.notValid()) {
            sql.append(" NOT VALID");
        }
        return sql.toString();
    }

    private static String action(ReferentialAction action) {
        return action.name().replace('_', ' ');
    }

    private static String deferrability(Deferrability deferrability) {
        return switch (deferrability) {
            case NOT_DEFERRABLE -> "";
            case DEFERRABLE_INITIALLY_IMMEDIATE -> " DEFERRABLE";
            case DEFERRABLE_INITIALLY_DEFERRED -> " DEFERRABLE INITIALLY DEFERRED";
        };
    }

    private static String include(List<String> columns) {
        return columns.isEmpty() ? "" : " INCLUDE (" + names(columns) + ")";
    }

    // ---------------------------------------------------------------- indexes

    public static String createIndex(Index index) {
        return "CREATE "
                + (index.unique() ? "UNIQUE " : "")
                + "INDEX "
                + index.name().map(n -> name(n) + " ").orElse("")
                + indexBody(index);
    }

    /** Everything after the index name: {@code ON table USING method (keys) ...}. */
    public static String indexBody(Index index) {
        StringBuilder sql =
                new StringBuilder("ON ")
                        .append(index.table().toSql())
                        .append(" USING ")
                        .append(name(index.method()))
                        .append(" (")
                        .append(index.columns().stream().map(SqlWriter::indexKey).collect(Collectors.joining(", ")))
                        .append(')')
                        .append(include(index.include()));
        if (index.nullsNotDistinct()) {
            sql.append(" NULLS NOT DISTINCT");
        }
        index.predicate().ifPresent(predicate -> sql.append(" WHERE (").append(predicate.sql()).append(')'));
        return sql.toString();
    }

    private static String indexKey(IndexColumn key) {
        StringBuilder sql =
                new StringBuilder(
                        key.column().map(SqlWriter::name).orElseGet(() -> "(" + key.expression().orElseThrow().sql() + ")"));
        key.collation().ifPresent(collation -> sql.append(" COLLATE ").append(collation));
        key.operatorClass().ifPresent(operatorClass -> sql.append(' ').append(operatorClass));
        if (key.order() == SortOrder.DESC) {
            sql.append(" DESC");
        }
        NullsOrder usual = key.order() == SortOrder.DESC ? NullsOrder.FIRST : NullsOrder.LAST;
        if (key.nulls() != usual) {
            sql.append(" NULLS ").append(key.nulls().name());
        }
        return sql.toString();
    }

    // ---------------------------------------------------------------- sequences

    public static String createSequence(Sequence sequence) {
        return "CREATE " + persistence(sequence.persistence()) + "SEQUENCE " + sequence.name().toSql() + sequenceOptions(sequence);
    }

    /** The sequence's settings as SQL options, each preceded by a space. OWNED BY is not included. */
    public static String sequenceOptions(Sequence sequence) {
        StringBuilder sql = new StringBuilder();
        sequence.dataType().ifPresent(type -> sql.append(" AS ").append(type.toSql()));
        sequence.start().ifPresent(start -> sql.append(" START WITH ").append(start));
        sql.append(" INCREMENT BY ").append(sequence.increment());
        sql.append(sequence.minValue().map(v -> " MINVALUE " + v).orElse(" NO MINVALUE"));
        sql.append(sequence.maxValue().map(v -> " MAXVALUE " + v).orElse(" NO MAXVALUE"));
        sql.append(" CACHE ").append(sequence.cache());
        if (sequence.cycle()) {
            sql.append(" CYCLE");
        }
        return sql.toString();
    }

    public static String ownedBy(ColumnRef owner) {
        return owner.table().toSql() + "." + name(owner.column());
    }

    // ---------------------------------------------------------------- whole objects

    public static String createEnum(EnumType type) {
        return "CREATE TYPE "
                + type.name().toSql()
                + " AS ENUM ("
                + type.labels().stream().map(SqlWriter::literal).collect(Collectors.joining(", "))
                + ")";
    }

    /**
     * CREATE TABLE with the columns and the given constraints inline. Other constraints are left
     * for separate ALTER TABLE statements, as {@code pg_dump} does.
     */
    public static String createTable(Table table, List<Constraint> inline) {
        List<String> elements = new ArrayList<>();
        table.columns().forEach(column -> elements.add(column(column)));
        inline.forEach(constraint -> elements.add(constraint(constraint)));
        StringBuilder sql =
                new StringBuilder("CREATE ")
                        .append(persistence(table.persistence()))
                        .append("TABLE ")
                        .append(table.name().toSql())
                        .append(" (");
        if (!elements.isEmpty()) {
            sql.append("\n    ").append(String.join(",\n    ", elements)).append('\n');
        }
        sql.append(')');
        if (!table.inherits().isEmpty()) {
            sql.append(" INHERITS (")
                    .append(table.inherits().stream().map(n -> n.toSql()).collect(Collectors.joining(", ")))
                    .append(')');
        }
        table.partitionBy().ifPresent(partitioning -> sql.append(" PARTITION BY ").append(partitioning));
        return sql.toString();
    }

    public static String addConstraint(Table table, Constraint constraint) {
        return "ALTER TABLE " + table.name().toSql() + " ADD " + constraint(constraint);
    }

    private static String persistence(Persistence persistence) {
        return switch (persistence) {
            case PERMANENT -> "";
            case UNLOGGED -> "UNLOGGED ";
            case TEMPORARY -> "TEMPORARY ";
        };
    }

    /**
     * The whole catalog as a script that rebuilds it on an empty database, in an order that
     * satisfies every dependency: types, sequences, tables with their valid CHECK constraints,
     * NOT VALID checks, primary and unique keys, indexes, foreign keys, sequence ownership.
     */
    public static String script(Catalog catalog) {
        List<String> statements = new ArrayList<>();
        catalog.enums().values().forEach(type -> statements.add(createEnum(type)));
        catalog.sequences().values().forEach(sequence -> statements.add(createSequence(sequence)));
        for (Table table : catalog.tables().values()) {
            List<Constraint> inline =
                    table.constraints().stream().filter(c -> c instanceof Check check && !check.notValid()).toList();
            statements.add(createTable(table, inline));
        }
        for (Table table : catalog.tables().values()) {
            table.constraints().stream()
                    .filter(c -> c instanceof Check check && check.notValid())
                    .forEach(c -> statements.add(addConstraint(table, c)));
        }
        for (Table table : catalog.tables().values()) {
            table.constraints().stream()
                    .filter(c -> c instanceof PrimaryKey || c instanceof Unique)
                    .forEach(c -> statements.add(addConstraint(table, c)));
        }
        catalog.indexes().values().forEach(index -> statements.add(createIndex(index)));
        for (Table table : catalog.tables().values()) {
            table.constraints().stream()
                    .filter(ForeignKey.class::isInstance)
                    .forEach(c -> statements.add(addConstraint(table, c)));
        }
        for (Sequence sequence : catalog.sequences().values()) {
            sequence.ownedBy()
                    .ifPresent(owner -> statements.add("ALTER SEQUENCE " + sequence.name().toSql() + " OWNED BY " + ownedBy(owner)));
        }
        return statements.isEmpty() ? "" : String.join(";\n\n", statements) + ";\n";
    }
}
