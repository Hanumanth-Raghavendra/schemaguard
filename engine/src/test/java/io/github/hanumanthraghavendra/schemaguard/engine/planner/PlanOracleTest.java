    static Stream<Case> cases() throws IOException {
        List<Case> cases = new ArrayList<>();
        int number = 0;
        for (RulesTest.Case example : RulesTest.cases().toList()) {
            number++;
            for (PlanOptions options : List.of(PlanOptions.direct(), PlanOptions.safe())) {
                String name = String.format("%03d %s %s", number, options.route(), example);
                cases.add(new Case(name, example.before(), example.after(), options));
            }
        }
        for (String[] extra : EXTRA) {
            for (PlanOptions options : List.of(PlanOptions.direct(), PlanOptions.safe())) {
                cases.add(new Case(extra[0] + " " + options.route(), extra[1], extra[2], options));
            }
        }
        String before = fixture("before_pg_dump_16.sql");
        String after = fixture("after_pg_dump_16.sql");
        Catalog from = RulesTest.catalog(before);
        Catalog to = RulesTest.catalog(after);
        List<Rename> renames = SchemaDiff.compare(from, to).changes().stream().flatMap(c -> Rename.of(c).stream()).toList();
        assertThat(renames).hasSize(3);
        for (PlanOptions options : List.of(PlanOptions.direct(), PlanOptions.safe())) {
            cases.add(new Case("evolution " + options.route(), before, after, options));
            cases.add(new Case("evolution " + options.route() + " with renames", before, after, options.withRenames(renames)));
        }
        return cases.stream();
    }

    private static String fixture(String file) throws IOException {
        try (InputStream in = PlanOracleTest.class.getResourceAsStream("/golden/evolution/" + file)) {
            assertThat(in).as("test resource %s", file).isNotNull();
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    /**
     * What still separates two schemas after a plan has run, leaving out what no plan can do:
     * column order, and the changes the plan itself reported as not planned.
     */
    static List<String> remaining(Catalog reached, Catalog wanted, MigrationPlan plan) {
        List<Class<?>> unplanned = new ArrayList<>(plan.unplanned().stream().map(item -> (Class<?>) item.change().getClass()).toList());
        boolean enumRebuild = unplanned.contains(Change.EnumValueRemoved.class) || unplanned.contains(Change.EnumValuesReordered.class);
        return SchemaDiff.compare(reached, wanted).changes().stream()
                .filter(change -> !change.cosmetic())
                .filter(change -> !(change instanceof Change.ColumnOrderChanged))
                .filter(change -> Rename.of(change).isEmpty())
                .filter(change -> !unplanned.contains(change.getClass()))
                // Without the rebuild of the type, values added before a removed one end up elsewhere.
                .filter(change -> !(enumRebuild && change instanceof Change.EnumValuesReordered))
                .map(ChangeFormatter::format)
                .toList();
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("cases")
    void theEngineAgreesThatThePlanReachesTheNewSchema(Case example) {
        Catalog before = RulesTest.catalog(example.before());
        Catalog after = RulesTest.catalog(example.after());
        MigrationPlan plan = Planner.plan(before, after, example.options());

        CatalogResult reached = CatalogBuilder.fromSql(SqlWriter.script(before) + plan.toSql());
        assumeTrue(reached.diagnostics().isEmpty(), () -> "the parser does not read every statement of this plan yet: " + reached.diagnostics());
        assertThat(remaining(reached.catalog(), after, plan)).as("plan:\n%s", plan.toSql()).isEmpty();
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("cases")
    void postgresAgreesThatThePlanReachesTheNewSchema(Case example) throws IOException, InterruptedException {
        assumeTrue(PostgresOracle.available(), "set SG_PG_ORACLE=1 and the PG* variables to run plans on a real server");
        MigrationPlan plan = Planner.plan(RulesTest.catalog(example.before()), RulesTest.catalog(example.after()), example.options());

        Catalog reached = PostgresOracle.schemaAfter(USER_FUNCTION, example.before(), plan.toSql());
        Catalog wanted = PostgresOracle.schemaAfter(USER_FUNCTION, example.after());
        assertThat(remaining(reached, wanted, plan)).as("plan:\n%s", plan.toSql()).isEmpty();
    }

    @Test
    void onTheSafeRouteNoStepBlocksWritesWhileItWorksThroughATableUnlessItSaysSo() throws IOException {
        for (Case example : cases().filter(c -> c.options().route() == PlanOptions.Route.SAFE).toList()) {
            MigrationPlan plan = Planner.plan(RulesTest.catalog(example.before()), RulesTest.catalog(example.after()), example.options());
            for (Step step : plan.steps()) {
                boolean onExistingTable = step.table().filter(table -> plan.diff().before().table(table).isPresent()).isPresent();
                boolean blocksForLong =
                        step.operation()
                                .filter(operation -> operation.work().growsWithTable())
                                .flatMap(operation -> operation.lock())
                                .filter(lock -> lock.blocksWrites())
                                .isPresent();
                if (onExistingTable && blocksForLong) {
                    assertThat(step.cautions()).as("%s: %s", example, step.sql()).isNotEmpty();
                }
            }
        }
    }
