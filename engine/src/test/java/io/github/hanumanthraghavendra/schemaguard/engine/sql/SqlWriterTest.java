package io.github.hanumanthraghavendra.schemaguard.engine.sql;

import static org.assertj.core.api.Assertions.assertThat;

import io.github.hanumanthraghavendra.schemaguard.engine.catalog.CatalogBuilder;
import io.github.hanumanthraghavendra.schemaguard.engine.catalog.CatalogResult;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Catalog;
import io.github.hanumanthraghavendra.schemaguard.engine.model.QualifiedName;
import io.github.hanumanthraghavendra.schemaguard.engine.model.Table;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

/**
 * The writer's promise: what it writes, the parser reads back as the same objects. The same
 * scripts were also loaded into PostgreSQL 16 and dumped again, giving identical catalogs.
 */
class SqlWriterTest {

    private static Catalog catalog(String sql) {
        CatalogResult result = CatalogBuilder.fromSql(sql);
        assertThat(result.diagnostics()).as("diagnostics for: %s", sql).isEmpty();
        return result.catalog();
    }

    private static Table table(String sql) {
        return catalog(sql).tables().values().iterator().next();
    }

    @ParameterizedTest
    @ValueSource(
            strings = {
                "shop/pg_dump_16.sql",
                "names/pg_dump_16.sql",
                "names/source.sql",
                "migrations/pg_dump_16.sql",
                "evolution/before_pg_dump_16.sql",
                "evolution/after_pg_dump_16.sql"
            })
    void aWrittenCatalogReadsBackEqual(String path) throws IOException {
        Catalog original;
        try (InputStream in = SqlWriterTest.class.getResourceAsStream("/golden/" + path)) {
            original = CatalogBuilder.fromSql(new String(in.readAllBytes(), StandardCharsets.UTF_8)).catalog();
        }
        assertThat(catalog(SqlWriter.script(original))).isEqualTo(original);
    }

    @Test
    void anEmptyCatalogIsAnEmptyScript() {
        assertThat(SqlWriter.script(Catalog.empty())).isEmpty();
    }

    @Test
    void columns() {
        Table table =
                table(
                        """
                        CREATE TABLE t (
                            a text COLLATE "C" DEFAULT 'x' NOT NULL,
                            b int GENERATED BY DEFAULT AS IDENTITY,
                            c int GENERATED ALWAYS AS (b * 2) STORED,
                            d timestamp DEFAULT (now() AT TIME ZONE 'utc'),
                            e varchar(10) DEFAULT ''::character varying,
                            "Mixed Case" int GENERATED ALWAYS AS IDENTITY
                        )
                        """);
        assertThat(table.columns().stream().map(SqlWriter::column))
                .containsExactly(
                        "a text COLLATE \"C\" DEFAULT 'x' NOT NULL",
                        "b integer GENERATED BY DEFAULT AS IDENTITY NOT NULL",
                        "c integer GENERATED ALWAYS AS (b * 2) STORED",
                        "d timestamp without time zone DEFAULT (now() at time zone 'utc')",
                        "e character varying(10) DEFAULT ''::character varying",
                        "\"Mixed Case\" integer GENERATED ALWAYS AS IDENTITY NOT NULL");
    }

    @Test
    void constraints() {
        Table table =
                table(
                        """
                        CREATE TABLE p (id int PRIMARY KEY, a int, b int, UNIQUE (a, b));
                        CREATE TABLE t (
                            x int, y int, z int,
                            CONSTRAINT t_pk PRIMARY KEY (x) INCLUDE (y) DEFERRABLE INITIALLY DEFERRED,
                            CONSTRAINT t_u UNIQUE NULLS NOT DISTINCT (y) DEFERRABLE,
                            CONSTRAINT t_fk FOREIGN KEY (y, z) REFERENCES p (a, b) MATCH FULL
                                ON DELETE SET NULL (y) ON UPDATE CASCADE NOT VALID,
                            CONSTRAINT t_check CHECK (z > 0) NO INHERIT NOT VALID
                        );
                        DROP TABLE p CASCADE;
                        """);
        assertThat(table.constraints().stream().map(SqlWriter::constraint))
                .containsExactly(
                        "CONSTRAINT t_check CHECK (z > 0) NO INHERIT NOT VALID",
                        "CONSTRAINT t_pk PRIMARY KEY (x) INCLUDE (y) DEFERRABLE INITIALLY DEFERRED",
                        "CONSTRAINT t_u UNIQUE NULLS NOT DISTINCT (y) DEFERRABLE");
    }

    @Test
    void foreignKeys() {
        Catalog catalog =
                catalog(
                        """
                        CREATE TABLE p (id int PRIMARY KEY, a int, b int, UNIQUE (a, b));
                        CREATE TABLE t (y int, z int,
                            CONSTRAINT t_fk FOREIGN KEY (y, z) REFERENCES p (a, b) MATCH FULL
                                ON DELETE SET NULL (y) ON UPDATE CASCADE DEFERRABLE NOT VALID,
                            CONSTRAINT t_plain FOREIGN KEY (y) REFERENCES p);
                        """);
        Table table = catalog.table(new QualifiedName("public", "t")).orElseThrow();
        assertThat(table.constraints().stream().map(SqlWriter::constraint))
                .containsExactly(
                        "CONSTRAINT t_fk FOREIGN KEY (y, z) REFERENCES public.p (a, b) MATCH FULL ON DELETE SET NULL (y)"
                                + " ON UPDATE CASCADE DEFERRABLE NOT VALID",
                        "CONSTRAINT t_plain FOREIGN KEY (y) REFERENCES public.p (id)");
    }

    @Test
    void indexes() {
        Catalog catalog =
                catalog(
                        """
                        CREATE TABLE t (a text, b int, c jsonb);
                        CREATE UNIQUE INDEX "Odd Name" ON t USING btree
                            (lower(a) COLLATE "C" text_pattern_ops DESC NULLS LAST, (b + 1) NULLS FIRST, b DESC)
                            INCLUDE (c) NULLS NOT DISTINCT WHERE b > 0;
                        CREATE INDEX ON t USING gin (c jsonb_path_ops);
                        """);
        assertThat(catalog.indexes().values().stream().map(SqlWriter::createIndex))
                .containsExactly(
                        "CREATE UNIQUE INDEX \"Odd Name\" ON public.t USING btree ((lower(a)) COLLATE \"C\" text_pattern_ops DESC NULLS LAST,"
                                + " (b + 1) NULLS FIRST, b DESC) INCLUDE (c) NULLS NOT DISTINCT WHERE (b > 0)",
                        "CREATE INDEX t_c_idx ON public.t USING gin (c jsonb_path_ops)");
    }

    @Test
    void enumsSequencesAndTables() {
        Catalog catalog =
                catalog(
                        """
                        CREATE TYPE mood AS ENUM ('ok', 'it''s');
                        CREATE UNLOGGED SEQUENCE s AS integer INCREMENT -2 CYCLE;
                        CREATE TABLE p (x int) PARTITION BY RANGE (x);
                        CREATE TABLE c () INHERITS (p);
                        """);
        assertThat(SqlWriter.createEnum(catalog.enums().values().iterator().next()))
                .isEqualTo("CREATE TYPE public.mood AS ENUM ('ok', 'it''s')");
        assertThat(SqlWriter.createSequence(catalog.sequences().values().iterator().next()))
                .isEqualTo(
                        "CREATE UNLOGGED SEQUENCE public.s AS integer START WITH -1 INCREMENT BY -2"
                                + " MINVALUE -2147483648 MAXVALUE -1 CACHE 1 CYCLE");
        assertThat(SqlWriter.createTable(catalog.table(new QualifiedName("public", "p")).orElseThrow(), List.of()))
                .isEqualTo("CREATE TABLE public.p (\n    x integer\n) PARTITION BY range (x)");
        assertThat(SqlWriter.createTable(catalog.table(new QualifiedName("public", "c")).orElseThrow(), List.of()))
                .isEqualTo("CREATE TABLE public.c () INHERITS (public.p)");
    }
}
