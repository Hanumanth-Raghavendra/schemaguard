CREATE SCHEMA shop;
CREATE TYPE shop.order_status AS ENUM ('pending', 'paid', 'shipped', 'cancelled');
CREATE TABLE shop.customers (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    full_name varchar(200) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    tags text[] DEFAULT '{}'::text[],
    meta jsonb DEFAULT '{}'::jsonb NOT NULL,
    CONSTRAINT customers_email_key UNIQUE (email),
    CONSTRAINT customers_email_check CHECK (email ~~ '%@%')
);
CREATE TABLE shop.orders (
    id serial PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES shop.customers (id) ON DELETE CASCADE,
    status shop.order_status NOT NULL DEFAULT 'pending',
    total numeric(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    discount numeric(5,2),
    note text COLLATE "C",
    placed_at timestamp(3) without time zone DEFAULT CURRENT_TIMESTAMP,
    total_with_tax numeric GENERATED ALWAYS AS (total * 1.18) STORED,
    CONSTRAINT discount_range CHECK (discount IS NULL OR (discount >= 0 AND discount <= 100))
);
CREATE TABLE shop.order_items (
    order_id integer NOT NULL,
    line_no smallint NOT NULL,
    sku char(8) NOT NULL,
    qty integer NOT NULL DEFAULT 1,
    price double precision,
    PRIMARY KEY (order_id, line_no),
    FOREIGN KEY (order_id) REFERENCES shop.orders (id) ON UPDATE CASCADE ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);
CREATE UNLOGGED TABLE shop.events (id bigserial, payload jsonb, at timestamptz DEFAULT now());
CREATE TABLE "Mixed Case" ("Id" int PRIMARY KEY, "select" text, bits bit varying(8), iv interval day to second, t time with time zone, by_default int GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE shop.audit (id bigint NOT NULL, at date NOT NULL, what text) PARTITION BY RANGE (at);
CREATE TABLE shop.audit_2026 PARTITION OF shop.audit FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
CREATE INDEX orders_customer_idx ON shop.orders (customer_id);
CREATE INDEX orders_open_idx ON shop.orders (placed_at DESC) WHERE status <> 'shipped';
CREATE UNIQUE INDEX customers_lower_email_idx ON shop.customers (lower(email));
CREATE INDEX customers_meta_idx ON shop.customers USING gin (meta jsonb_path_ops);
CREATE INDEX customers_name_idx ON shop.customers (full_name text_pattern_ops, created_at DESC NULLS LAST) INCLUDE (email);
CREATE INDEX orders_expr_idx ON shop.orders ((total - COALESCE(discount, 0)), status);
CREATE SEQUENCE shop.invoice_no START 1000 INCREMENT 5 MAXVALUE 999999 CYCLE;
CREATE SEQUENCE shop.countdown INCREMENT -1 MINVALUE -100 MAXVALUE -1;
COMMENT ON TABLE shop.orders IS 'Customer orders; it''s commented';
CREATE VIEW shop.open_orders AS SELECT id, total FROM shop.orders WHERE status = 'pending';
CREATE FUNCTION shop.touch() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.placed_at := now(); RETURN NEW; END; $$;
CREATE TRIGGER orders_touch BEFORE UPDATE ON shop.orders FOR EACH ROW EXECUTE FUNCTION shop.touch();
