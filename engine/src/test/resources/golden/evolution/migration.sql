-- Version 1 to version 2. Every statement here is one the SchemaGuard parser reads, so the
-- catalog built from before.sql followed by this file can be checked against the real dump.

-- Enumerated types
ALTER TYPE app.status ADD VALUE 'scheduled' BEFORE 'published';
ALTER TYPE app.status ADD VALUE 'deleted';
ALTER TYPE app.role RENAME VALUE 'writer' TO 'author';

-- Users: a renamed column, a widened type, a dropped and an added column, a new check
ALTER TABLE app.users RENAME COLUMN display_name TO full_name;
ALTER TABLE app.users ALTER COLUMN email TYPE text;
ALTER TABLE app.users DROP COLUMN bio;
ALTER TABLE app.users ADD COLUMN last_login timestamptz;
ALTER TABLE app.users ADD CONSTRAINT users_email_lower CHECK (email = lower(email)) NOT VALID;

-- Posts: column changes, constraint changes, and index changes
ALTER TABLE app.posts ALTER COLUMN body SET NOT NULL;
ALTER TABLE app.posts ALTER COLUMN views TYPE bigint;
ALTER TABLE app.posts ALTER COLUMN status SET DEFAULT 'scheduled';
ALTER TABLE app.posts ADD COLUMN slug text;
ALTER TABLE app.posts ADD CONSTRAINT posts_slug_key UNIQUE (slug);
ALTER TABLE app.posts RENAME CONSTRAINT posts_views_check TO posts_views_nonnegative;
ALTER TABLE app.posts ADD CONSTRAINT posts_published_check
    CHECK (status <> 'published' OR published_at IS NOT NULL) NOT VALID;
ALTER TABLE app.posts VALIDATE CONSTRAINT posts_published_check;
ALTER TABLE app.posts DROP CONSTRAINT posts_author_id_fkey;
ALTER TABLE app.posts ADD CONSTRAINT posts_author_id_fkey
    FOREIGN KEY (author_id) REFERENCES app.users ON DELETE CASCADE;
DROP INDEX app.posts_status_idx;
CREATE INDEX posts_status_idx ON app.posts (status) WHERE status <> 'archived';
DROP INDEX app.posts_title_idx;
CREATE INDEX posts_lower_title_idx ON app.posts (lower(title));

-- Tables: one renamed, one created, two dropped
ALTER TABLE app.audit_log RENAME TO activity_log;
CREATE TABLE app.comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL REFERENCES app.posts ON DELETE CASCADE,
    author_id bigint REFERENCES app.users ON DELETE SET NULL,
    body text NOT NULL CHECK (char_length(body) <= 5000),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX comments_post_idx ON app.comments (post_id, created_at DESC);
DROP TABLE app.post_tags;
DROP TABLE app.tags;

-- Sequences
DROP SEQUENCE app.invoice_number;
CREATE SEQUENCE app.order_number AS integer START 1 INCREMENT 10;
