-- A schema built the way a real project builds one: created, then changed by a run of
-- migrations. Every kind of change the catalog models appears here at least once.

CREATE SCHEMA app;
CREATE SCHEMA archive;

CREATE TYPE app.status AS ENUM ('new', 'done');
ALTER TYPE app.status ADD VALUE 'active' BEFORE 'done';
ALTER TYPE app.status ADD VALUE IF NOT EXISTS 'new';
ALTER TYPE app.status ADD VALUE 'archived';
ALTER TYPE app.status ADD VALUE 'draft' AFTER 'new';
ALTER TYPE app.status RENAME VALUE 'done' TO 'finished';

CREATE TABLE app.users (
    id serial PRIMARY KEY,
    email text NOT NULL,
    name text,
    age int,
    legacy_code text UNIQUE
);

CREATE TABLE app.posts (
    id bigint NOT NULL,
    user_id int NOT NULL REFERENCES app.users,
    title varchar(100),
    body text,
    views int DEFAULT 0,
    score int,
    weight int,
    state app.status DEFAULT 'new',
    doubled int GENERATED ALWAYS AS (score * 2) STORED,
    CHECK (views >= 0),
    CHECK (score < weight)
);
CREATE INDEX posts_user_idx ON app.posts (user_id);
CREATE INDEX posts_score_idx ON app.posts (score) INCLUDE (weight);
CREATE INDEX posts_title_idx ON app.posts (lower(title));
CREATE INDEX posts_body_idx ON app.posts (lower(body)) WHERE views > 10;
CREATE UNIQUE INDEX posts_id_uidx ON app.posts (id);

-- Adding
ALTER TABLE app.posts ADD CONSTRAINT posts_pkey PRIMARY KEY USING INDEX posts_id_uidx;
ALTER TABLE app.posts
    ADD COLUMN created_at timestamptz NOT NULL DEFAULT now(),
    ADD COLUMN slug text UNIQUE,
    ADD COLUMN seq serial;
ALTER TABLE app.posts ADD CONSTRAINT title_len CHECK (char_length(title) > 3) NOT VALID;
ALTER TABLE app.posts VALIDATE CONSTRAINT title_len;
ALTER TABLE app.posts ADD FOREIGN KEY (user_id) REFERENCES app.users (id) ON DELETE CASCADE NOT VALID;
ALTER TABLE app.posts ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Changing
ALTER TABLE app.posts ALTER COLUMN title TYPE text, ALTER COLUMN views SET DEFAULT 1, ALTER COLUMN body SET NOT NULL;
ALTER TABLE app.posts ALTER COLUMN state DROP DEFAULT;
ALTER TABLE app.users ALTER COLUMN email DROP NOT NULL;
ALTER TABLE app.users ALTER COLUMN age TYPE bigint USING age::bigint;

-- Renaming
ALTER TABLE app.posts RENAME COLUMN score TO points;
ALTER TABLE app.posts RENAME COLUMN views TO view_count;
ALTER TABLE app.posts RENAME CONSTRAINT title_len TO posts_title_len;
ALTER TABLE app.users RENAME COLUMN id TO user_pk;
ALTER TABLE app.users RENAME TO accounts;

-- Dropping
ALTER TABLE app.posts DROP COLUMN weight;
ALTER TABLE app.posts DROP COLUMN points CASCADE;
ALTER TABLE app.accounts DROP CONSTRAINT users_legacy_code_key;
ALTER TABLE app.accounts DROP COLUMN IF EXISTS nope, DROP COLUMN name;
ALTER TABLE app.posts DROP CONSTRAINT posts_user_id_fkey;
DROP INDEX app.posts_title_idx;

-- Moving to another schema
CREATE TABLE app.old_logs (id serial PRIMARY KEY, msg text, post_id bigint REFERENCES app.posts);
CREATE INDEX ON app.old_logs (msg);
ALTER TABLE app.old_logs SET SCHEMA archive;
CREATE SEQUENCE archive.ticket START 100;
ALTER SEQUENCE archive.ticket OWNED BY archive.old_logs.msg;

-- Dropping with CASCADE
CREATE TABLE app.tmp (id int PRIMARY KEY, st app.status);
CREATE TABLE app.tmp_child (tmp_id int REFERENCES app.tmp);
DROP TABLE app.tmp CASCADE;

CREATE TYPE app.color AS ENUM ('r', 'g');
CREATE TABLE app.paint (id int, c app.color, other int);
DROP TYPE app.color CASCADE;

CREATE SEQUENCE app.counter;
CREATE TABLE app.uses_counter (n bigint DEFAULT nextval('app.counter'));
DROP SEQUENCE app.counter CASCADE;

DROP TABLE IF EXISTS app.nope;
