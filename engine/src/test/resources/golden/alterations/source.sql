-- Statements that change an object in place: the ones a migration plan is made of.
-- CatalogOracleTest builds a catalog from this script and from PostgreSQL's dump of the
-- database it leaves behind (pg_dump_16.sql); the two must be equal.

CREATE SCHEMA ops;

-- ---------------------------------------------------------------- ALTER INDEX ... RENAME TO
CREATE TABLE ops.jobs (
    id integer NOT NULL,
    queue text NOT NULL,
    payload text,
    CONSTRAINT jobs_pkey PRIMARY KEY (id),
    CONSTRAINT jobs_queue_key UNIQUE (queue, id)
);
CREATE INDEX jobs_queue_idx ON ops.jobs (queue);
CREATE INDEX jobs_payload_idx ON ops.jobs (lower(payload));

ALTER INDEX ops.jobs_queue_idx RENAME TO jobs_by_queue;
-- The index of a constraint takes the constraint along.
ALTER INDEX ops.jobs_pkey RENAME TO jobs_primary;
ALTER INDEX IF EXISTS ops.no_such_index RENAME TO whatever;
-- PostgreSQL accepts ALTER INDEX for a table as well.
CREATE TABLE ops.scratch (a integer);
ALTER INDEX ops.scratch RENAME TO notes;

-- ---------------------------------------------------------------- identity and generated columns
CREATE TABLE ops.readings (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    other_id integer GENERATED ALWAYS AS IDENTITY,
    celsius numeric(5,2),
    fahrenheit numeric(6,2) GENERATED ALWAYS AS (celsius * 9 / 5 + 32) STORED,
    kelvin numeric(6,2) GENERATED ALWAYS AS (celsius + 273.15) STORED
);
ALTER TABLE ops.readings ALTER COLUMN id SET GENERATED ALWAYS;
ALTER TABLE ops.readings ALTER COLUMN other_id SET GENERATED BY DEFAULT;
ALTER TABLE ops.readings ALTER COLUMN fahrenheit DROP EXPRESSION;
ALTER TABLE ops.readings ALTER COLUMN celsius DROP EXPRESSION IF EXISTS;

-- ---------------------------------------------------------------- SET LOGGED, SET UNLOGGED
CREATE TABLE ops.cache (
    id serial PRIMARY KEY,
    job_id integer REFERENCES ops.jobs (id),
    body text
);
-- The sequence behind the serial column becomes unlogged with its table.
ALTER TABLE ops.cache SET UNLOGGED;
ALTER TABLE ops.cache SET UNLOGGED;

CREATE UNLOGGED TABLE ops.sessions (id bigserial PRIMARY KEY, token text);
CREATE UNLOGGED TABLE ops.session_events (session_id bigint REFERENCES ops.sessions (id), at timestamptz);
ALTER TABLE ops.sessions SET LOGGED;
ALTER TABLE ops.session_events SET LOGGED;

-- ---------------------------------------------------------------- INHERIT, NO INHERIT
CREATE TABLE ops.events (
    at timestamptz NOT NULL,
    kind text,
    CONSTRAINT events_kind_check CHECK (kind <> '')
);
CREATE TABLE ops.events_2026 (
    at timestamptz NOT NULL,
    kind text,
    source text,
    CONSTRAINT events_kind_check CHECK ((kind <> ''))
);
CREATE TABLE ops.events_old (at timestamptz NOT NULL, kind text, CONSTRAINT events_kind_check CHECK (kind <> ''));
ALTER TABLE ops.events_2026 INHERIT ops.events;
ALTER TABLE ops.events_old INHERIT ops.events;
ALTER TABLE ops.events_old NO INHERIT ops.events;

-- ---------------------------------------------------------------- ALTER SEQUENCE
CREATE SEQUENCE ops.ticket_number;
ALTER SEQUENCE ops.ticket_number INCREMENT BY 10 MAXVALUE 99990 CYCLE CACHE 5;

-- A new type moves a limit only if the limit was the old type's own.
CREATE SEQUENCE ops.small_numbers;
ALTER SEQUENCE ops.small_numbers AS smallint;
CREATE SEQUENCE ops.bounded AS smallint MAXVALUE 100;
ALTER SEQUENCE ops.bounded AS integer;

CREATE SEQUENCE ops.countdown INCREMENT BY -1;
ALTER SEQUENCE ops.countdown AS integer;
ALTER SEQUENCE ops.countdown MINVALUE -500 START WITH -10 RESTART;

CREATE SEQUENCE ops.unbounded MINVALUE 5 MAXVALUE 50 CYCLE;
ALTER SEQUENCE ops.unbounded NO MAXVALUE NO CYCLE RESTART WITH 7;

-- A new direction alone leaves both limits where they are.
CREATE SEQUENCE ops.turned;
ALTER SEQUENCE ops.turned INCREMENT BY -2;

CREATE SEQUENCE ops.owned_later;
ALTER SEQUENCE ops.owned_later START WITH 100 OWNED BY ops.jobs.id;
ALTER SEQUENCE IF EXISTS ops.no_such_sequence INCREMENT BY 2;
