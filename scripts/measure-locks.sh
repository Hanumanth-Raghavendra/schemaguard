#!/usr/bin/env bash
# Measures on a running PostgreSQL what the engine's risk rules otherwise would have to take on
# trust. The results are kept as fixtures and a test compares the engine's knowledge with them.
#
#   operations  what each kind of schema change does to a table:
#                 - the strongest lock it takes on the table it changes (t)
#                 - the strongest lock it takes on a table that t references (p)
#                 - whether it rewrites t         (pg_relation_filenode changes)
#                 - whether it reads every row    (the scan counters in pg_stat_xact_user_tables go up)
#   types       whether ALTER COLUMN ... TYPE rewrites the table, for pairs of types
#   conflicts   which table lock modes conflict with each other
#   functions   which built-in functions are volatile (a volatile column default forces a rewrite)
#
# Each statement runs inside BEGIN ... ROLLBACK and is measured before the rollback, so every
# measurement starts from the same schema. The two CONCURRENTLY statements cannot run in a
# transaction: a second session holds them up while a third reads the locks they already hold.
#
# Usage, from the repository root (PGHOST, PGPORT, PGUSER as usual; PGBIN optional):
#   scripts/measure-locks.sh operations > engine/src/test/resources/locks/pg16-operations.tsv
#   scripts/measure-locks.sh types      > engine/src/test/resources/locks/pg16-type-changes.tsv
#   scripts/measure-locks.sh conflicts  > engine/src/test/resources/locks/pg16-lock-conflicts.tsv
#   scripts/measure-locks.sh functions  > engine/src/main/resources/io/github/hanumanthraghavendra/schemaguard/engine/rules/pg16-function-volatility.tsv
set -euo pipefail

bin="${PGBIN:+$PGBIN/}"
db="sg_locks_$$"
# A fixed, non-UTC time zone: timestamp -> timestamptz skips the rewrite only when the session is in UTC.
export PGTZ="Asia/Kolkata"

psql() { "${bin}psql" -X -q -At -v ON_ERROR_STOP=1 "$@"; }
trim() { sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' <<<"$1"; }
create_database() { psql -d postgres -c "DROP DATABASE IF EXISTS ${db}" -c "CREATE DATABASE ${db}" 2>/dev/null; }
drop_database() { psql -d postgres -c "DROP DATABASE ${db}"; }
version() { psql -d "$db" -c 'SHOW server_version' | cut -d' ' -f1; }

modes="'AccessShareLock','RowShareLock','RowExclusiveLock','ShareUpdateExclusiveLock','ShareLock','ShareRowExclusiveLock','ExclusiveLock','AccessExclusiveLock'"

strongest() {  # SQL: the strongest lock the session selected by $2 holds on the relation with oid $1
    echo "coalesce((SELECT mode FROM pg_locks WHERE $2 AND locktype = 'relation' AND granted AND relation = $1
            ORDER BY array_position(ARRAY[$modes], mode) DESC LIMIT 1), 'none')"
}

operations() {
    create_database
    psql -d "$db" <<'SQL'
CREATE TYPE mood AS ENUM ('a', 'b');
CREATE TABLE p (id int PRIMARY KEY, u int);
CREATE TABLE t (
    id int NOT NULL, a int, b varchar(10), c text, n numeric(10,2), p_id int, nn int NOT NULL, d int DEFAULT 1, m mood,
    g int, idc int GENERATED BY DEFAULT AS IDENTITY, gen int GENERATED ALWAYS AS (g + 1) STORED,
    CONSTRAINT t_g_check CHECK (g IS NOT NULL));
-- Added afterwards: PostgreSQL ignores NOT VALID inside CREATE TABLE, the constraint would be valid.
ALTER TABLE t ADD CONSTRAINT t_a_check CHECK (a > 0) NOT VALID;
ALTER TABLE t ADD CONSTRAINT t_fk FOREIGN KEY (p_id) REFERENCES p NOT VALID;
CREATE INDEX t_a_idx ON t (a);
CREATE INDEX t_b_idx ON t (b);
CREATE UNIQUE INDEX t_id_uidx ON t (id);
SQL
    echo "# What each schema change does on PostgreSQL $(version). Written by scripts/measure-locks.sh; do not edit."
    echo "# operation | lock on the changed table t | lock on p, which t references | rewrite | scan | statement"

    while IFS='|' read -r name ddl; do
        [ -z "$name" ] && continue
        name="$(trim "$name")"; ddl="$(trim "$ddl")"
        measured=$(psql -d "$db" <<SQL
SELECT 't'::regclass::oid AS t_oid, 'p'::regclass::oid AS p_oid, pg_relation_filenode('t') AS t_node \gset
BEGIN;
SELECT seq_scan + coalesce(idx_scan, 0) AS scans FROM pg_stat_xact_user_tables WHERE relid = :t_oid \gset
$ddl;
SELECT $(strongest :t_oid "pid = pg_backend_pid()") || '|' || $(strongest :p_oid "pid = pg_backend_pid()") || '|' ||
       CASE WHEN pg_relation_filenode(:t_oid) IS NULL THEN 'dropped'
            WHEN pg_relation_filenode(:t_oid) <> :t_node THEN 'rewrite' ELSE 'no-rewrite' END || '|' ||
       CASE WHEN (SELECT seq_scan + coalesce(idx_scan, 0) FROM pg_stat_xact_user_tables WHERE relid = :t_oid) > :scans
            THEN 'scan' ELSE 'no-scan' END;
ROLLBACK;
SQL
)
        echo "$name|$measured|$ddl"
    done <<'CASES'
ADD_COLUMN                    | ALTER TABLE t ADD COLUMN x int
ADD_COLUMN_CONSTANT_DEFAULT   | ALTER TABLE t ADD COLUMN x int DEFAULT 5
ADD_COLUMN_NOT_NULL_DEFAULT   | ALTER TABLE t ADD COLUMN x int NOT NULL DEFAULT 5
ADD_COLUMN_STABLE_DEFAULT     | ALTER TABLE t ADD COLUMN x timestamptz DEFAULT now()
ADD_COLUMN_VOLATILE_DEFAULT   | ALTER TABLE t ADD COLUMN x double precision DEFAULT random()
ADD_COLUMN_SERIAL             | ALTER TABLE t ADD COLUMN x serial
ADD_COLUMN_IDENTITY           | ALTER TABLE t ADD COLUMN x int GENERATED ALWAYS AS IDENTITY
ADD_COLUMN_GENERATED          | ALTER TABLE t ADD COLUMN x int GENERATED ALWAYS AS (a * 2) STORED
ADD_COLUMN_WITH_FOREIGN_KEY   | ALTER TABLE t ADD COLUMN x int REFERENCES p
DROP_COLUMN                   | ALTER TABLE t DROP COLUMN c
ALTER_TYPE_REWRITE            | ALTER TABLE t ALTER COLUMN a TYPE bigint
ALTER_TYPE_NO_REWRITE         | ALTER TABLE t ALTER COLUMN b TYPE varchar(20)
ALTER_COLLATION               | ALTER TABLE t ALTER COLUMN c TYPE text COLLATE "C"
ALTER_COLLATION_INDEXED       | ALTER TABLE t ALTER COLUMN b TYPE varchar(10) COLLATE "C"
SET_NOT_NULL                  | ALTER TABLE t ALTER COLUMN a SET NOT NULL
SET_NOT_NULL_WITH_VALID_CHECK | ALTER TABLE t ALTER COLUMN g SET NOT NULL
DROP_NOT_NULL                 | ALTER TABLE t ALTER COLUMN nn DROP NOT NULL
SET_DEFAULT                   | ALTER TABLE t ALTER COLUMN a SET DEFAULT 1
DROP_DEFAULT                  | ALTER TABLE t ALTER COLUMN d DROP DEFAULT
ADD_IDENTITY                  | ALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY
SET_IDENTITY                  | ALTER TABLE t ALTER COLUMN idc SET GENERATED ALWAYS
DROP_IDENTITY                 | ALTER TABLE t ALTER COLUMN idc DROP IDENTITY
DROP_EXPRESSION               | ALTER TABLE t ALTER COLUMN gen DROP EXPRESSION
ADD_CHECK                     | ALTER TABLE t ADD CONSTRAINT x CHECK (a < 100)
ADD_CHECK_NOT_VALID           | ALTER TABLE t ADD CONSTRAINT x CHECK (a < 100) NOT VALID
VALIDATE_CHECK                | ALTER TABLE t VALIDATE CONSTRAINT t_a_check
ADD_FOREIGN_KEY               | ALTER TABLE t ADD CONSTRAINT x FOREIGN KEY (a) REFERENCES p
ADD_FOREIGN_KEY_NOT_VALID     | ALTER TABLE t ADD CONSTRAINT x FOREIGN KEY (a) REFERENCES p NOT VALID
VALIDATE_FOREIGN_KEY          | ALTER TABLE t VALIDATE CONSTRAINT t_fk
ALTER_FOREIGN_KEY             | ALTER TABLE t ALTER CONSTRAINT t_fk DEFERRABLE
ADD_UNIQUE                    | ALTER TABLE t ADD CONSTRAINT x UNIQUE (a)
ADD_PRIMARY_KEY               | ALTER TABLE t ADD PRIMARY KEY (id)
ADD_PRIMARY_KEY_NULLABLE      | ALTER TABLE t ADD PRIMARY KEY (a)
ADD_CONSTRAINT_USING_INDEX    | ALTER TABLE t ADD CONSTRAINT x UNIQUE USING INDEX t_id_uidx
ADD_PRIMARY_KEY_USING_INDEX   | ALTER TABLE t ADD CONSTRAINT x PRIMARY KEY USING INDEX t_id_uidx
DROP_CONSTRAINT               | ALTER TABLE t DROP CONSTRAINT t_g_check
DROP_FOREIGN_KEY              | ALTER TABLE t DROP CONSTRAINT t_fk
RENAME_CONSTRAINT             | ALTER TABLE t RENAME CONSTRAINT t_a_check TO y
CREATE_INDEX                  | CREATE INDEX x ON t (c)
DROP_INDEX                    | DROP INDEX t_a_idx
RENAME_INDEX                  | ALTER INDEX t_a_idx RENAME TO y
RENAME_COLUMN                 | ALTER TABLE t RENAME COLUMN a TO z
RENAME_TABLE                  | ALTER TABLE t RENAME TO t2
SET_SCHEMA                    | CREATE SCHEMA other; ALTER TABLE t SET SCHEMA other
SET_UNLOGGED                  | ALTER TABLE t SET UNLOGGED
DROP_TABLE                    | DROP TABLE t
CREATE_TABLE_WITH_FOREIGN_KEY | CREATE TABLE fresh (p_id int REFERENCES p)
ADD_ENUM_VALUE                | ALTER TYPE mood ADD VALUE 'c'
RENAME_ENUM_VALUE             | ALTER TYPE mood RENAME VALUE 'a' TO 'z'
CASES

    # CONCURRENTLY: a blocker holds a lock that the statement has to wait out; an observer then
    # reads the locks the waiting statement already holds. The scan is read from the table's
    # cumulative counters once the statement has finished.
    while IFS='|' read -r name ddl; do
        name="$(trim "$name")"; ddl="$(trim "$ddl")"
        before=$(psql -d "$db" -c "SELECT seq_scan + coalesce(idx_scan, 0) FROM pg_stat_user_tables WHERE relname = 't'")
        psql -d "$db" -c "BEGIN; LOCK TABLE t IN ROW EXCLUSIVE MODE; SELECT pg_sleep(4); ROLLBACK;" >/dev/null &
        blocker=$!
        psql -d "$db" -c "SELECT pg_sleep(1)" >/dev/null
        psql -d "$db" -c "$ddl" >/dev/null &
        runner=$!
        psql -d "$db" -c "SELECT pg_sleep(1.5)" >/dev/null
        mode=$(psql -d "$db" -c "SELECT $(strongest "'t'::regclass" "pid = (SELECT pid FROM pg_stat_activity
               WHERE query LIKE '%CONCURRENTLY%' AND pid <> pg_backend_pid() LIMIT 1)")")
        wait "$blocker" "$runner"
        psql -d "$db" -c "SELECT pg_sleep(1.5)" >/dev/null
        after=$(psql -d "$db" -c "SELECT seq_scan + coalesce(idx_scan, 0) FROM pg_stat_user_tables WHERE relname = 't'")
        scan="no-scan"; [ "$after" -gt "$before" ] && scan="scan"
        echo "$name|$mode|none|no-rewrite|$scan|$ddl"
    done <<'CASES'
CREATE_INDEX_CONCURRENTLY     | CREATE INDEX CONCURRENTLY x ON t (c)
DROP_INDEX_CONCURRENTLY       | DROP INDEX CONCURRENTLY t_a_idx
CASES
    drop_database
}

types() {
    create_database
    echo "# Whether ALTER COLUMN ... TYPE rewrites the table on PostgreSQL $(version), session time zone ${PGTZ}."
    echo "# Written by scripts/measure-locks.sh; do not edit."
    echo "# from | to | rewrite"
    while IFS='|' read -r from to; do
        [ -z "$from" ] && continue
        from="$(trim "$from")"; to="$(trim "$to")"
        result=$(psql -d "$db" <<SQL
DROP TABLE IF EXISTS c;
CREATE TABLE c (x $from);
SELECT pg_relation_filenode('c') AS node \gset
BEGIN;
ALTER TABLE c ALTER COLUMN x TYPE $to USING x::$to;
SELECT CASE WHEN pg_relation_filenode('c') <> :node THEN 'rewrite' ELSE 'no-rewrite' END;
ROLLBACK;
SQL
)
        echo "$from|$to|$result"
    done <<'CASES'
varchar(10) | varchar(20)
varchar(10) | varchar(5)
varchar(10) | varchar
varchar(10) | text
varchar     | text
varchar     | varchar(10)
text        | varchar
text        | varchar(10)
varchar(10) | char(10)
char(10)    | char(20)
char(10)    | char(5)
char(10)    | varchar(10)
char(10)    | text
integer     | bigint
bigint      | integer
smallint    | integer
integer     | numeric
bigint      | numeric
integer     | text
numeric(10,2) | numeric(12,2)
numeric(10,2) | numeric(8,2)
numeric(10,2) | numeric(10,4)
numeric(10,2) | numeric(12,4)
numeric(10,2) | numeric
numeric     | numeric(10,2)
numeric(10) | numeric(12)
numeric(10) | numeric(12,2)
real        | double precision
timestamp   | timestamp(3)
timestamp(3) | timestamp(6)
timestamp(3) | timestamp
timestamp(6) | timestamp(3)
timestamptz(3) | timestamptz
timestamptz | timestamptz(3)
timestamp   | timestamptz
timestamptz | timestamp
time(3)     | time
time        | time(3)
timetz(3)   | timetz
interval(3) | interval
interval    | interval(3)
varbit(5)   | varbit(10)
varbit(10)  | varbit(5)
varbit(5)   | varbit
bit(5)      | varbit(5)
json        | jsonb
text        | jsonb
cidr        | inet
