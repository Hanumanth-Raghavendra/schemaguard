date        | timestamp
uuid        | text
boolean     | integer
integer[]   | bigint[]
varchar(10)[] | varchar(20)[]
varchar(10)[] | text[]
text[]      | varchar[]
CASES
    drop_database
}

conflicts() {
    create_database
    psql -d "$db" -c "CREATE TABLE lk (id int)"
    echo "# Which table lock modes conflict on PostgreSQL $(version). Written by scripts/measure-locks.sh; do not edit."
    echo "# held | requested | result"
    names=("ACCESS SHARE" "ROW SHARE" "ROW EXCLUSIVE" "SHARE UPDATE EXCLUSIVE" "SHARE" "SHARE ROW EXCLUSIVE" "EXCLUSIVE" "ACCESS EXCLUSIVE")
    for held in "${names[@]}"; do
        psql -d "$db" -c "BEGIN; LOCK TABLE lk IN $held MODE; SELECT pg_sleep(3); ROLLBACK;" >/dev/null &
        holder=$!
        psql -d "$db" -c "SELECT pg_sleep(1)" >/dev/null
        for requested in "${names[@]}"; do
            if psql -d "$db" -c "BEGIN; LOCK TABLE lk IN $requested MODE NOWAIT; ROLLBACK;" >/dev/null 2>&1; then
                echo "$held|$requested|compatible"
            else
                echo "$held|$requested|conflict"
            fi
        done
        wait "$holder"
    done
    drop_database
}

functions() {
    echo "# Built-in functions of PostgreSQL $(psql -d postgres -c 'SHOW server_version' | cut -d' ' -f1): v = at least one"
    echo "# variant is volatile, s = every variant is stable or immutable. Written by scripts/measure-locks.sh; do not edit."
    psql -d postgres -c "SELECT proname || '|' || CASE WHEN bool_or(provolatile = 'v') THEN 'v' ELSE 's' END
                         FROM pg_proc WHERE pronamespace = 'pg_catalog'::regnamespace AND prokind = 'f'
                         GROUP BY proname ORDER BY proname COLLATE \"C\""
}

case "${1:-}" in
    operations) operations ;;
    types) types ;;
    conflicts) conflicts ;;
    functions) functions ;;
    *) echo "usage: $0 operations|types|conflicts|functions" >&2; exit 2 ;;
esac
